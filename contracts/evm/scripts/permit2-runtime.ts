// Renders test/mocks/Permit2Runtime.sol from the vendored Permit2 runtime the local deploy installs, so the fuzz
// harness deploys byte-identical code. Run it to regenerate; its test fails while the committed file differs.
import { join } from "node:path"

const ROOT = join(import.meta.dir, "..")
export const VENDORED = join(ROOT, "../../packages/deployer/bytecode/permit2.json")
export const GENERATED = join(ROOT, "test/mocks/Permit2Runtime.sol")

export type Vendored = { keccak: string; code: string }

export function render(v: Vendored): string {
	if (!/^0x[0-9a-f]{64}$/.test(v.keccak)) throw new Error("permit2.json: malformed keccak")
	if (!/^0x(?:[0-9a-f]{2})+$/.test(v.code)) throw new Error("permit2.json: malformed code")
	return `// SPDX-License-Identifier: Apache-2.0
// Generated by scripts/permit2-runtime.ts from packages/deployer/bytecode/permit2.json; do not edit.
pragma solidity >=0.8.27;

/// Permit2's deployed runtime. Its domain separator is cached for Sepolia's chain id and canonical address; on any
/// other chain id it is rebuilt from \`block.chainid\` and the address the code runs at.
library Permit2Runtime {
    bytes32 internal constant KECCAK = ${v.keccak};
    bytes internal constant CODE =
        hex"${v.code.slice(2)}";
}
`
}

if (import.meta.main) {
	await Bun.write(GENERATED, render((await Bun.file(VENDORED).json()) as Vendored))
}
